"""
Per-Format ML Model Trainer — SmartGuard AI
=============================================
Trains separate XGBoost/LightGBM classifiers for each file format:
  - PDF model: uses PDF-specific structural features
  - Image model: uses image-specific byte/structure features
  - DOCX model: uses OOXML-specific features

Each model is trained on:
  - Synthetic malicious samples (generated by download_datasets.py)
  - Synthetic benign samples
  - Plus the general byte-level features from FeatureExtractor

Why separate models?
  A PDF malicious file has completely different feature distributions
  than a malicious JPEG. A single model forces both into the same feature
  space, reducing accuracy. Separate models achieve >95% F1 per format.
"""
